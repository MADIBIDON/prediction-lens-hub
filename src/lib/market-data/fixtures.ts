const NOW_MS = new Date("2026-04-25").getTime();
const STEP_MS = (30 * 24 * 60 * 60 * 1000) / 19; // 30-day window, 20 points

function genChart(seed: number, endProb: number, vol = 0.04): ProbabilityPoint[] {
  const points: ProbabilityPoint[] = [];
  let p = Math.max(0.02, Math.min(0.97, endProb - ((seed * 7) % 14 - 7) / 100));
  for (let i = 0; i < 20; i++) {
    if (i > 0) {
      const noise =
        (Math.sin(seed + i * 0.8) + Math.cos(seed * 0.4 + i * 0.5)) * vol;
      p = Math.max(0.02, Math.min(0.97, p + noise * 0.4));
    }
    points.push({
      timestamp: Math.round(NOW_MS - (19 - i) * STEP_MS),
      probability: Number(p.toFixed(3)),
    });
  }
  points[19].probability = endProb;
  return points;
}

function binary(prob: number): MarketOutcome[] {
  return [
    { id: "yes", label: "Yes", probability: prob, colorKey: "green" },
    {
      id: "no",
      label: "No",
      probability: Number((1 - prob).toFixed(3)),
      colorKey: "red",
    },
  ];
}

function mkNews(
  id: string,
  source: string,
  headline: string,
  relatedMarketId: string,
  probabilityImpact: number,
  category: MarketCategory,
  region?: MarketRegion
): MarketNewsItem {
  return {
    id,
    source,
    headline,
    publishedAt: "2026-04-25T08:00:00Z",
    relatedMarketId,
    probabilityImpact,
    probabilityImpactWindow: "24h",
    category,
    region,
    credibility: Math.abs(probabilityImpact) > 3 ? "high" : "medium",
  };
}

function mkMarket(
  id: string,
  title: string,
  shortTitle: string,
  description: string,
  platform: PredictionPlatform,
  category: MarketCategory,
  region: MarketRegion,
  countryCodes: string[],
  probability: number,
  change24h: number,
  change7d: number,
  volume24h: number,
  volumeTotal: number,
  liquidity: number,
  spread: number,
  closeDate: string,
  tags: string[],
  outcomes: MarketOutcome[],
  chartSeed: number,
  chartVol: number,
  relatedNews: MarketNewsItem[],
  visualFallback: MarketVisualFallback,
  extra: {
    imageUrl?: string;
    subcategory?: string;
    oracleScore?: number;
    resolutionClarity?: "clear" | "ambiguous" | "disputed";
  } = {}
): OracleMarket {
  return {
    id,
    sourceId: id,
    slug: id,
    title,
    shortTitle,
    description,
    platform,
    isFixture: true,
    category,
    subcategory: extra.subcategory,
    status: "active",
    probability,
    probabilityChange24h: change24h,
    probabilityChange7d: change7d,
    volume24h,
    volumeTotal,
    liquidity,
    spread,
    closeDate,
    createdAt: "2026-01-15T00:00:00Z",
    updatedAt: "2026-04-25T00:00:00Z",
    imageUrl: extra.imageUrl,
    visualFallback,
    region,
    countryCodes,
    tags,
    outcomes,
    chartData: genChart(chartSeed, probability, chartVol),
    relatedNews,
    sourceUrl: "#",
    oracleScore: extra.oracleScore,
    resolutionClarity: extra.resolutionClarity ?? "clear",
  };
}

